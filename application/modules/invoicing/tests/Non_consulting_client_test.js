'use strict';
const assert = require('node:assert/strict');
const items = require('../../../../assets/js/invoicing/non-consulting-form.js');
const calculator = require('../../../../assets/js/invoicing/consulting.js');
assert.deepEqual(items.calculate([{qty: '1.25', harga: '800.00'}], '0.55'), {amount: '1000.55', lines: [100000]});
assert.deepEqual(items.calculate([{qty: '0.01', harga: '0.50'}, {qty: '1', harga: '0'}], '0'), {amount: '0.01', lines: [1, 0]});
assert.equal(items.calculate([{qty: '1', harga: '9999999999999.99'}], '0').amount, '9999999999999.99');
for (const qty of ['0', '-1', '1.234', '1000000', 'bad', '']) assert.throws(() => items.calculate([{qty, harga: '1'}], '0'));
for (const price of ['-1', '1.234', 'bad']) assert.throws(() => items.calculate([{qty: '1', harga: price}], '0'));
assert.throws(() => items.calculate([], '0'));
assert.throws(() => items.calculate([{qty: '999999.99', harga: '9999999999999.99'}], '0'));
const amount = items.calculate([{qty: '1', harga: '19975200'}], '0').amount;
assert.equal(calculator.totals(amount, 'PKP').receivable, 2217247200);
for (const type of ['WAPU', 'KB', 'UMKM']) assert.equal(calculator.totals(amount, type).receivable, 1997520000);
const events = {}, bodyEvents = {}, buttonEvents = {};
let changed = 0;
const row = {querySelector(selector) { return {'[name$="[qty]"]': {value: '1.25'}, '[name$="[harga]"]': {value: '800.00'}, '[data-item-total]': this.total}[selector]; }, total: {textContent: ''}};
const body = {children: [row], querySelectorAll() { return this.children; }, contains: () => true, appendChild(child) { this.children.push(child); }, addEventListener: (name, cb) => { bodyEvents[name] = cb; }};
let focused = false;
const addButton = {focus() { focused = true; }, addEventListener: (name, cb) => { buttonEvents[name] = cb; }};
const form = {querySelector(selector) { return {'[data-invoice-items]': body, '[name="biaya_kirim"]': {value: '0.55'}, '[data-add-item]': addButton}[selector]; }, addEventListener(name, cb) { events[name] = cb; }};
const newRow = {setAttribute() {}, querySelector(selector) { return {'textarea': {focus() { focused = true; }}, '[name$="[qty]"]': {value: '1'}, '[name$="[harga]"]': {value: '0'}, '[data-item-total]': {textContent: ''}}[selector]; }, remove() { body.children = body.children.filter(child => child !== this); }};
form.ownerDocument = {createElement: () => newRow};
const options = items.bind(form); options.onChange(() => { changed++; });
assert.equal(options.amount(), '1000.55'); assert.equal(row.total.textContent, '1,000.00');
events.input({target: {}}); assert.equal(changed, 1);
assert.equal(typeof bodyEvents.click, 'function'); assert.equal(typeof buttonEvents.click, 'function');
buttonEvents.click(); assert.equal(body.children.length, 2); assert.equal(focused, true);
assert.equal(options.amount(), '1000.55'); assert.match(newRow.innerHTML, /item\[1\]\[nama\]/);
focused = false;
bodyEvents.click({target: {closest: () => ({closest: () => newRow})}});
assert.equal(body.children.length, 1); assert.equal(focused, true); assert.equal(changed, 3);
console.log('PASS: non consulting item cents, tax parity, validation and live preview binding');
